#!/usr/bin/env python3
"""Generates Sources/UsageCore/ModelPrices.generated.swift from site/data/models.json.

Only models with an input and an output list price are included. cacheRead / cacheWrite are optional
(USD per million tokens); when absent the app charges that part at the input price.

  python3 scripts/gen-prices.py          write the file
  python3 scripts/gen-prices.py --check  exit 1 when the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "site" / "data" / "models.json"
TARGET = ROOT / "Sources" / "UsageCore" / "ModelPrices.generated.swift"


def number(value):
    return repr(float(value))


def render():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    lines = [
        "// Generated by scripts/gen-prices.py from site/data/models.json. Do not edit by hand.",
        "// USD per million tokens, vendor list prices. Reviewed " + data["lastReviewed"] + ".",
        "extension ModelPrices {",
        '    static let reviewed = "' + data["lastReviewed"] + '"',
        "    static let entries: [ModelPrice] = [",
    ]
    for m in data["models"]:
        if m.get("input") is None or m.get("output") is None:
            continue
        parts = ['id: "%s"' % m["id"], "input: " + number(m["input"]), "output: " + number(m["output"])]
        if m.get("cacheRead") is not None:
            parts.append("cacheRead: " + number(m["cacheRead"]))
        if m.get("cacheWrite") is not None:
            parts.append("cacheWrite: " + number(m["cacheWrite"]))
        lines.append("        ModelPrice(" + ", ".join(parts) + "),")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("ModelPrices.generated.swift is out of date: run python3 scripts/gen-prices.py", file=sys.stderr)
            sys.exit(1)
    else:
        TARGET.write_text(text, encoding="utf-8")
